window.ruComponent = function (name) {
  if (!name) return "Не указано";
  const dict = window.ISSUES_RU.components;
  const n = String(name).toUpperCase().trim();
  if (dict[n]) return dict[n];
  const head = n.split(":")[0].trim();
  if (dict[head]) return dict[head];
  return name;
};
